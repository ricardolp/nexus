export type BrazilianUF = (typeof BRAZILIAN_STATES)[number]['uf'];

const stateNameByUF = new Map<string, string>(BRAZILIAN_STATES.map((s) => [s.uf, s.name]));

export function formatUF(uf?: string | null): string {
  if (!uf) return '—';
  const name = stateNameByUF.get(uf.toUpperCase());
  return name ? `${uf.toUpperCase()} — ${name}` : uf.toUpperCase();
}
